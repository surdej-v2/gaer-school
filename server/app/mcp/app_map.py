def sections() -> list[dict]:
    routes = app_map()["routes"]
    return [{**s, "anchors": routes.get(s["path"], {}).get("anchors", [])} for s in SECTIONS]


def search(q: str, limit: int = 5) -> list[dict]:
    words = [w for w in q.lower().replace("?", " ").split() if len(w) > 2]
    scored = []
    for s in sections():
        hay = " ".join([s["title"], s["purpose"], s["api"], s["source"], KEYWORDS.get(s["path"], ""),
                        " ".join(s["anchors"])]).lower()
        score = sum(3 if w in s["title"].lower() else 1 for w in words if w in hay)
        if score:
            scored.append((score, s))
    return [s for _, s in sorted(scored, key=lambda x: -x[0])[:limit]]
